#!/usr/bin/env bash
set -euo pipefail

DIR="$(cd "$(dirname "$0")" && pwd)"
OUT_TS="$DIR/../src/usb/fastLoaderStub.ts"
ELF="/tmp/amba_fast_loader.elf"
BIN="/tmp/amba_fast_loader.bin"

arm-linux-gnueabi-gcc -march=armv6 -marm -Os -ffreestanding -nostdlib -fno-builtin \
  -fno-stack-protector -T "$DIR/fast_loader.ld" -o "$ELF" "$DIR/fast_loader.c"
arm-linux-gnueabi-objcopy -O binary "$ELF" "$BIN"

python3 - "$BIN" "$OUT_TS" <<'PY'
import hashlib, sys

bin_path, out_path = sys.argv[1], sys.argv[2]
data = open(bin_path, "rb").read()
sha = hashlib.sha256(data).hexdigest()

lines = []
for i in range(0, len(data), 16):
    chunk = ", ".join(f"0x{b:02x}" for b in data[i:i+16])
    lines.append(f"  {chunk},")

ts = f"""/*
 * Auto-generated by web/firmware/build.sh from web/firmware/fast_loader.c.
 * Bare-metal ARMv6 EP1 Bulk-OUT DMA receiver for Ambarella A5s (loaded at 0xc0090000).
 * Size: {len(data)} bytes | SHA-256: {sha}
 */

export const FAST_LOADER_ADDR = 0xc0090000;
export const FAST_LOADER_MAGIC_CMD = 0x414d4241; // "AMBA"
export const FAST_LOADER_MAGIC_OK = 0x4f4b4159; // "OKAY"

export const FAST_CMD_PING = 1;
export const FAST_CMD_WRITE_MEM = 2;
export const FAST_CMD_WRITE_WORD = 3;
export const FAST_CMD_EXEC = 4;
export const FAST_CMD_READ_WORD = 5;

export const FAST_LOADER_SHA256 = '{sha}';

export const FAST_LOADER_STUB = new Uint8Array([
{chr(10).join(lines)}
]);

const CRC32_TABLE = (() => {{
  const t = new Uint32Array(256);
  for (let i = 0; i < 256; i++) {{
    let c = i;
    for (let b = 0; b < 8; b++) {{
      c = (c & 1) ? (0xedb88320 ^ (c >>> 1)) : (c >>> 1);
    }}
    t[i] = c >>> 0;
  }}
  return t;
}})();

export function crc32(data: Uint8Array): number {{
  let crc = 0xffffffff;
  for (let i = 0; i < data.byteLength; i++) {{
    crc = CRC32_TABLE[(crc ^ data[i]) & 0xff] ^ (crc >>> 8);
  }}
  return (crc ^ 0xffffffff) >>> 0;
}}
"""

open(out_path, "w").write(ts)
print(f"Generated {out_path} ({len(data)} bytes, sha256={sha})")
PY

rm -f "$ELF" "$BIN"

UBI_OUT_TS="$DIR/../src/flasher/ubiatt2048.ts"
UBI_BIN="/tmp/amba_ubiatt2048"
arm-linux-gnueabi-gcc -march=armv6 -marm -Os -nostdlib -static \
  -Wl,--build-id=none -Wl,-z,norelro -o "$UBI_BIN" "$DIR/ubiatt2048.c"
arm-linux-gnueabi-strip --strip-all "$UBI_BIN"

python3 - "$UBI_BIN" "$UBI_OUT_TS" <<'PY'
import hashlib, sys

bin_path, out_path = sys.argv[1], sys.argv[2]
data = open(bin_path, "rb").read()
sha = hashlib.sha256(data).hexdigest()

lines = []
for i in range(0, len(data), 16):
    chunk = ", ".join(f"0x{b:02x}" for b in data[i:i+16])
    lines.append(f"  {chunk},")

ts = f"""/*
 * Auto-generated by web/firmware/build.sh from web/firmware/ubiatt2048.c.
 * Zero-dependency ARMv6 Linux EABI ELF helper that attaches mtd9 with VID header
 * offset 2048 via UBI_IOCATT ioctl (BusyBox 1.23 ubiattach omits -O 2048).
 * Size: {len(data)} bytes | SHA-256: {sha}
 */

export const UBIATT2048_SHA256 = '{sha}';

export const UBIATT2048_BIN = new Uint8Array([
{chr(10).join(lines)}
]);
"""

open(out_path, "w").write(ts)
print(f"Generated {out_path} ({len(data)} bytes, sha256={sha})")
PY

rm -f "$UBI_BIN"
